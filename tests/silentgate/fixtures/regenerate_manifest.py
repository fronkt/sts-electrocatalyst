DECOMP_NOTE = '''# Files carrying force-DECOMPOSITION blocks. Each has ONE real force block and
# SIX contribution blocks in the identical `atom N type M force =` format, so a
# regex that scrapes force lines without delimiting blocks reads 7x the ionic
# steps and mixes partial forces into the census. None currently carries an
# adsorbate tag, so no archived CSV row is wrong -- but a per-step detector that
# inherits this bug is wrong on every one of them.'''


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def header_form_label(line):
    inv = "with-inversion" if ", with inversion," in line else "no-inversion"
    frac = "with-fractional-translation" if "fractional translation" in line else "bare"
    return "count-first, %s, %s" % (inv, frac)


def main():
    os.chdir(ROOT)
    out = [HEADER]
    for rel, pins, decides in FIXTURES:
        if not os.path.exists(rel):
            raise SystemExit("FATAL: fixture %s is missing" % rel)
        b = open(rel, "rb").read()
        lf = b.replace(b"\r\n", b"\n")
        blob = subprocess.run(["git", "hash-object", rel],
                              capture_output=True, text=True).stdout.strip()
        m = SYM.search(b)
        symline = m.group(0).decode("utf8", "replace").strip() if m else None
        nat = NAT.search(b)
        idx = b.find(b"Forces acting on atoms")
        region = b[idx:idx + 4000] if idx >= 0 else b
        fm = re.search(rb"^\s*atom\s+(\d+)\s+type", region, re.M)

        out.append("[[fixture]]")
        out.append('path = "%s"' % esc(rel))
        out.append('pins = "%s"' % esc(pins))
        out.append('decides = "%s"' % esc(decides))
        out.append('git_blob = "%s"' % blob)
        out.append('sha256_lf = "%s"' % hashlib.sha256(lf).hexdigest())
        out.append("bytes_lf = %d" % len(lf))
        out.append("")
        out.append("[fixture.structure]")
        out.append("pwscf_banner = %s" % ("true" if b"Program PWSCF" in b else "false"))
        if symline:
            out.append('symmetry_header = "%s"' % esc(symline))
            out.append('symmetry_header_form = "%s"' % header_form_label(symline))
            out.append("n_symops_in_header = %s" % m.group(1).decode())
        else:
            out.append('symmetry_header = ""')
            out.append('symmetry_header_form = "none"')
        out.append("no_symmetry_found = %s" % ("true" if b"No symmetry found" in b else "false"))
        out.append("n_force_block_headers = %d" % len(FHDR.findall(b)))
        out.append("n_contribution_block_headers = %d" % len(CONTRIB.findall(b)))
        out.append("n_force_lines = %d" % len(FLINE.findall(b)))
        out.append("n_atoms_cell = %s" % (nat.group(1).decode() if nat else "0"))
        out.append("first_force_atom_index = %s" % (fm.group(1).decode() if fm else "0"))
        out.append("nul_bytes = %d" % b.count(b"\x00"))
        out.append("negative_zero_tokens = %d" % b.count(b"-0.00000000"))
        out.append("job_done = %s" % ("true" if b"JOB DONE" in b else "false"))
        out.append("mpi_abort = %s" % ("true" if b"MPI_ABORT" in b else "false"))
        out.append("")

    files = [f for f in subprocess.run(["git", "ls-files", "runs/"], capture_output=True,
                                       text=True).stdout.split() if f.endswith(".out")]
    forms, nosym_only, neither, decomp = {}, 0, 0, []
    for f in files:
        b = open(f, "rb").read().replace(b"\r\n", b"\n")
        m = SYM.search(b)
        if m:
            key = re.sub(r"\d+", "N", m.group(0).decode("utf8", "replace").strip())
            forms[key] = forms.get(key, 0) + 1
        elif b"No symmetry found" in b:
            nosym_only += 1
        else:
            neither += 1
        if CONTRIB.search(b):
            decomp.append(f)

    out.append(CORPUS_NOTE)
    out.append("[corpus]")
    out.append("tracked_out_files = %d" % len(files))
    out.append("with_symmetry_header = %d" % sum(forms.values()))
    out.append("no_symmetry_found_only = %d" % nosym_only)
    out.append("neither_marker = %d" % neither)
    out.append("with_force_decomposition_blocks = %d" % len(decomp))
    out.append("")
    out.append(HEADER_FORM_NOTE)
    out.append("[corpus.header_forms]")
    for k, v in sorted(forms.items(), key=lambda kv: -kv[1]):
        out.append('"%s" = %d' % (esc(k), v))
    out.append("")
    out.append(DECOMP_NOTE)
    out.append("[corpus.force_decomposition_files]")
    out.append("paths = [")
    for f in decomp:
        out.append('  "%s",' % esc(f))
    out.append("]")
    out.append("")

    with open(DST, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote %s" % os.path.relpath(DST, ROOT))
    print("  fixtures %d | tracked .out %d | header forms %d | decomposition files %d"
          % (len(FIXTURES), len(files), len(forms), len(decomp)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
