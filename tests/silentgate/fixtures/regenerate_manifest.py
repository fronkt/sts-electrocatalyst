#!/usr/bin/env python3
"""Regenerate tests/silentgate/fixtures/manifest.toml from the tracked corpus.

Run from anywhere:  python tests/silentgate/fixtures/regenerate_manifest.py

Every value in the manifest is MEASURED here, never transcribed. Run this when a
test tells you to -- a new symmetry-header form appeared, a decomposition file
was added, a fixture legitimately changed -- and commit the diff so the change is
visible rather than silent.

WHAT THIS DELIBERATELY DOES NOT COMPUTE
---------------------------------------
No census. No LOCKED verdict. No per-atom / per-axis / per-step exact-zero
determination. Those are `silentgate/readers/*` and `silentgate/census.py`, which
are core: "written and committed only by the entrant" (docs/43:1840). This
records file SHAPE -- hashes, byte counts, which marker lines a file carries, how
many force blocks and contribution blocks it has -- and stops there. Numeric
census expectations enter the suite later as golden files generated by the
entrant's own core.

AUTHORSHIP: written by AI as "tests and fixtures" under the A9.1 :1840 permitted
list.
"""
