"""LIT-3(a): zero-DFT *OOH fingerprint classification (docs/43 AMENDMENT 5, A5.3a).

Registered scope: every archived *OOH geometry is classified by O-O distance
as the PRIMARY fingerprint (hydroperoxo *O-OH ~1.37-1.45 A vs superoxo *OO-H
~1.30-1.32 A, Inico 2024), with Bader (QTAIM) charge via pp.x as the SECONDARY
check. The Bader leg is NOT computed here: Inico's charge thresholds are
Bader-defined and may not be compared against Loewdin values without
recalibration, and no `.save` directories survive on disk -- every run listed
in the `bader_todo` section needs one fixed-geometry SCF (bounded within the
~150-SCF A5.1a/A5.3a regeneration budget) plus pp.x before any charge
fingerprint exists. A scaling-residual audit accompanies the classification
(Man 3.2 +/- 0.2/0.4 as an RPBE-population outlier flag ONLY, never a
per-state pass/fail -- docs/41 P9's functional-mismatch caveat applies).

What is classified: every `s0_OOH*.out` RELAXATION under runs/ (production
runs, the Cr basin restart, the P10 orientation runs, the block-1A cellsym
rows that have returned). Fixed-geometry SCF outputs (the P7 U-ladders, the
docs/41 probe variants, the Cr k-mesh bridges, the Hessian stencil) share
their parent relaxation's geometry by construction and are listed as excluded
duplicates rather than classified twice.

Conventions REUSED, not reinvented:
  - energy QC: dft.qe_qc.trusted_energy_ev / scan (the production gate);
  - CHE referencing for the scaling audit: hea_oer.referencing.delta_G
    (ZPE-TS: OH +0.35 / OOH +0.40 eV, Man 2011 / Valdes 2008) -- the
    slab energy cancels in dG_OOH - dG_OH but the same helper is used anyway;
  - geometry parsing: probe_decks.parse_input_deck / parse_final_coordinates;
  - magnetisation readout: build_cellsym_pilot.final_magnetisation.

Outputs (the .md is REGENERATED by this script -- never hand-edit it):
  docs/research/lit3_ooh_fingerprints.json
  docs/research/2026-08-12-lit3-ooh-fingerprints.md

Usage:
  PYTHONPATH=src python src/dft/lit3_ooh_fingerprints.py [--root .]
"""
